/**
 * generate-admin-dark-theme.mjs
 *
 * Writes the admin dark theme into app/globals.css (between the
 * ADMIN-DARK-THEME markers). Run after changing the palette below:
 *
 *   node scripts/generate-admin-dark-theme.mjs
 *
 * How it works: Tailwind v4 utilities read colours from CSS variables
 * (e.g. text-slate-900 → var(--color-slate-900)). Inside the admin content
 * area, dark mode re-points those variables to a navy palette, so every page
 * switches at once without per-element `dark:` classes. Solid button fills
 * (white text on a strong colour) are pinned separately so they stay readable.
 *
 * Applies to `.admin-theme[data-theme="dark"]`, and to
 * `.admin-theme[data-theme="system"]` when the device prefers dark.
 */
import { readFileSync, writeFileSync } from "node:fs";

/* Tints (50–300) become dark surfaces; strong shades (500–950) become light text tones. */
const palette = {
  slate: { 50: "#0b1220", 100: "#151f33", 200: "#243149", 300: "#334360", 400: "#5d6b85", 500: "#8a96ad", 600: "#a7b2c6", 700: "#c2cbdb", 800: "#d9dfea", 900: "#e9edf4", 950: "#f5f7fb" },
  "brand-blue": { 50: "#13213f", 100: "#182a52", 200: "#22386b", 300: "#3a5590", 400: "#5c80d6", 500: "#7898e4", 600: "#8eaaf0", 700: "#9fb7f2", 800: "#b9cbf5", 900: "#d2def9", 950: "#e6edfc" },
  "brand-orange": { 50: "#2c1a0c", 100: "#3a2210", 200: "#5a3517", 300: "#8a5222", 400: "#f58530", 500: "#f79a52", 600: "#f9ab6c", 700: "#fbb983", 800: "#fcc99f", 900: "#fdd9bb", 950: "#feeadb" },
  emerald: { 50: "#0c2a22", 100: "#103a2e", 200: "#165140", 500: "#34d399", 600: "#4ade9f", 700: "#6ee7b7", 800: "#a7f3d0", 900: "#d1fae5" },
  red: { 50: "#2f1216", 100: "#43181d", 200: "#6a2129", 400: "#f87171", 500: "#f87171", 600: "#fb8b8b", 700: "#fca5a5", 800: "#fecaca", 900: "#fee2e2" },
  rose: { 50: "#2f1220", 100: "#43182c", 200: "#6a2140", 700: "#fda4af", 800: "#fecdd3", 900: "#ffe4e6", 950: "#fff1f2" },
  amber: { 50: "#2b210b", 100: "#3a2c0e", 200: "#5c4513", 500: "#fbbf24", 600: "#fcc94a", 700: "#fcd34d", 800: "#fde68a", 900: "#fef3c7", 950: "#fffbeb" },
};

const SURFACE = "#111a2c"; // cards, inputs, panels (was white)

/* Solid fills that carry white text: keep them strong in dark mode. */
const solidFills = {
  "brand-blue-500": "#3f67d6", "brand-blue-600": "#3f67d6", "brand-blue-700": "#3459c2", "brand-blue-800": "#2c4ea8", "brand-blue-900": "#243f8a", "brand-blue-950": "#1b3170",
  "brand-orange-500": "#e9741a", "brand-orange-600": "#e9741a", "brand-orange-700": "#cf6312",
  "slate-700": "#334360", "slate-800": "#2a3956", "slate-900": "#24324d", "slate-950": "#1e2a42",
  "emerald-600": "#0f9f6e", "emerald-700": "#0c8a5f",
  "red-600": "#dc3b3b", "red-700": "#c02f2f", "rose-600": "#e0435e",
};

const variables = Object.entries(palette)
  .flatMap(([name, shades]) => Object.entries(shades).map(([shade, value]) => `  --color-${name}-${shade}: ${value};`))
  .concat([`  --admin-surface: ${SURFACE};`, "  color-scheme: dark;"])
  .join("\n");

const esc = (cls) => cls.replace(/[:/.[\]]/g, (c) => `\\${c}`);
const fillRules = (scope) =>
  Object.entries(solidFills)
    .map(([name, value]) => `${scope} .${esc(`bg-${name}`)}, ${scope} .${esc(`hover:bg-${name}`)}:hover { background-color: ${value}; }`)
    .concat(
      // Dimmed backdrops behind dialogs and drawers use the darkest greys at
      // partial opacity; keep them a dark veil rather than inverting to light.
      `${scope} [class*="bg-slate-950/"], ${scope} [class*="bg-slate-900/"] { background-color: rgb(2 6 16 / 0.6); }`,
    )
    .join("\n");

const css = `/* ADMIN-DARK-THEME:START — generated by scripts/generate-admin-dark-theme.mjs; do not edit by hand. */
.admin-theme[data-theme="dark"] {
${variables}
}
@media (prefers-color-scheme: dark) {
  .admin-theme[data-theme="system"] {
${variables.replace(/^/gm, "  ")}
  }
}
/* Text that has no colour class (typed input text, placeholders) follows the theme. */
.admin-theme { color: var(--color-slate-900); }
.admin-theme ::placeholder { color: var(--color-slate-400); opacity: 1; }

/* Cards, inputs and panels: white becomes the dark surface (text-white stays white). */
.admin-theme .bg-white, .admin-theme .hover\\:bg-white:hover, .admin-theme .focus\\:bg-white:focus { background-color: var(--admin-surface, #ffffff); }
.admin-theme [class*="bg-white/"] { background-color: color-mix(in oklab, var(--admin-surface, #ffffff) 92%, transparent); }

/* Solid buttons and badges keep strong fills so their white text stays readable. */
${fillRules('.admin-theme[data-theme="dark"]')}
@media (prefers-color-scheme: dark) {
${fillRules('.admin-theme[data-theme="system"]').replace(/^/gm, "  ")}
}
/* ADMIN-DARK-THEME:END */`;

const file = "app/globals.css";
let globals = readFileSync(file, "utf8");
const start = globals.indexOf("/* ADMIN-DARK-THEME:START");
const endMarker = "/* ADMIN-DARK-THEME:END */";
const end = globals.indexOf(endMarker);
globals = start >= 0 && end > start
  ? globals.slice(0, start) + css + globals.slice(end + endMarker.length)
  : `${globals.trimEnd()}\n\n${css}\n`;
writeFileSync(file, globals);
console.log(`admin dark theme written (${css.length} chars)`);
