create table if not exists public.trip_requests (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  full_name text not null check (char_length(full_name) between 2 and 120),
  email text not null check (position('@' in email) > 1),
  phone text not null check (char_length(phone) between 7 and 40),
  country text not null check (char_length(country) between 2 and 100),
  destinations text[] not null default '{}',
  services text[] not null default '{}',
  interests text[] not null default '{}',
  travel_start date,
  travel_end date,
  date_flexibility text,
  adults integer not null default 1 check (adults between 1 and 200),
  children integer not null default 0 check (children between 0 and 200),
  budget_currency text not null check (budget_currency in ('GHS','USD','GBP','EUR')),
  budget_basis text not null check (budget_basis in ('per-person','total-trip')),
  budget_range text not null check (char_length(budget_range) between 1 and 100),
  accommodation_style text,
  notes text,
  status text not null default 'new' check (status in ('new','reviewing','contacted','quoted','confirmed','closed')),
  policy_version text not null,
  policy_accepted_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists trip_requests_created_at_idx on public.trip_requests (created_at desc);
create index if not exists trip_requests_status_idx on public.trip_requests (status);
create index if not exists trip_requests_email_idx on public.trip_requests (lower(email));

alter table public.trip_requests enable row level security;
revoke all on table public.trip_requests from anon, authenticated;
revoke all on sequence public.trip_requests_id_seq from anon, authenticated;

create table if not exists public.package_reservations (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  package_slug text not null,
  package_title text not null,
  full_name text not null check (char_length(full_name) between 2 and 120),
  email text not null check (position('@' in email) > 1),
  phone text not null check (char_length(phone) between 7 and 40),
  emergency_contact_name text not null check (char_length(emergency_contact_name) between 2 and 120),
  emergency_contact_phone text not null check (char_length(emergency_contact_phone) between 7 and 40),
  travellers integer not null check (travellers between 1 and 200),
  dietary_requirements text,
  accessibility_requirements text,
  notes text,
  currency text not null default 'GHS',
  price_per_person integer not null check (price_per_person >= 0),
  total_price integer not null check (total_price >= 0),
  deposit_per_person integer not null check (deposit_per_person >= 0),
  deposit_due integer not null check (deposit_due >= 0),
  status text not null default 'pending-review' check (status in ('pending-review','confirmed-awaiting-deposit','deposit-paid','paid','waitlisted','cancelled')),
  payment_status text not null default 'not-requested' check (payment_status in ('not-requested','deposit-requested','deposit-paid','paid','refunded','partially-refunded')),
  promotional_media_consent boolean not null default false,
  media_notice_acknowledged_at timestamptz not null,
  policy_version text not null,
  policy_accepted_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (package_slug, email)
);

create index if not exists package_reservations_created_at_idx on public.package_reservations (created_at desc);
create index if not exists package_reservations_status_idx on public.package_reservations (status);
create index if not exists package_reservations_package_slug_idx on public.package_reservations (package_slug);

alter table public.package_reservations enable row level security;
revoke all on table public.package_reservations from anon, authenticated;
revoke all on sequence public.package_reservations_id_seq from anon, authenticated;